// Minimal service worker — exists mainly to satisfy Chrome's installability
// criteria (a registered SW with a fetch handler). Network-first with a
// same-origin GET cache fallback, so the app shell still loads if you're
// briefly offline; it deliberately does not try to cache API responses,
// since stale food/log/auth data would be actively misleading.
const CACHE_NAME = 'fittrack-shell-v1';

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.url.includes('/api/')) return;

  event.respondWith(
    fetch(request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        return response;
      })
      .catch(() => caches.match(request))
  );
});
